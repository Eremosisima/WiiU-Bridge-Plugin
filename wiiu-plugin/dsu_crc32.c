uint32_t dsu_crc32(const uint8_t *data, size_t length) {
    uint32_t crc = 0xFFFFFFFF;
    
    for (size_t i = 0; i < length; i++) {
        crc = crc32_table[(crc ^ data[i]) & 0xFF] ^ (crc >> 8);
    }
    
    return crc ^ 0xFFFFFFFF;
}

uint32_t dsu_crc32_packet(const uint8_t *packet, size_t packet_length) {
    if (!packet || packet_length < 12) {
        return 0;
    }
    
    // Create temporary buffer with CRC field zeroed
    uint8_t temp[256];
    if (packet_length > sizeof(temp)) {
        return 0;
    }
    
    memcpy(temp, packet, packet_length);
    
    // Zero out CRC field (bytes 8-11)
    temp[8] = 0;
    temp[9] = 0;
    temp[10] = 0;
    temp[11] = 0;
    
    return dsu_crc32(temp, packet_length);
}

int dsu_crc32_verify(const uint8_t *packet, size_t packet_length) {
    if (!packet || packet_length < 16) {
        return 0;
    }
    
    // Extract stored CRC
    uint32_t stored_crc;
    memcpy(&stored_crc, packet + 8, sizeof(uint32_t));
    
    // Calculate CRC
    uint32_t calculated_crc = dsu_crc32_packet(packet, packet_length);
    
    return stored_crc == calculated_crc;
}
